import assert from 'node:assert/strict';
import {setUser,env} from './fake-runtime';
import {GET as readRecords,POST as writeRecord} from '../app/api/admin/records/route';
import {GET as readAccess,POST as writeAccess} from '../app/api/admin/access/route';
import {GET as audit} from '../app/api/admin/audit/route';
import {publicCatalog} from '../lib/admin/catalog';
import {stays} from '../data/clustersData';
const origin='https://one-day-farming.test';
const req=(path:string,body?:unknown,from=origin)=>new Request(origin+path,{method:body?'POST':'GET',headers:body?{'Content-Type':'application/json',Origin:from}:{},body:body?JSON.stringify(body):undefined});
let checks=0;
function status(r:Response,expected:number){assert.equal(r.status,expected);checks++;}
setUser(null);status(await readRecords(req('/api/admin/records?cluster=mankulam&kind=stays')),401);
setUser('outsider@example.test');status(await readAccess(),403);
setUser('owner@example.test');
const grant={email:'alice@example.test',cluster:'mankulam',permissions:['stays','content'],active:true,version:0};
status(await writeAccess(req('/api/admin/access',grant)),200);
const m=((await (await readAccess()).json()) as {members:{id:string;bound:boolean}[]}).members[0];assert.equal(m.bound,false);checks++;
setUser('alice@example.test','alice-id');
status(await readRecords(req('/api/admin/records?cluster=mankulam&kind=stays')),200);
status(await readRecords(req('/api/admin/records?cluster=vattavada&kind=stays')),403);
status(await readRecords(req('/api/admin/records?cluster=mankulam&kind=products')),403);
status(await readAccess(),403);
status(await writeAccess(req('/api/admin/access',{...grant,email:'attacker@example.test'})),403);
const record={cluster:'mankulam',kind:'stays',recordId:'mankulam-stay',version:0,published:true,archived:false,payload:{...stays[0],title:'Updated Mankulam stay',clusterId:'vattavada'}};
status(await writeRecord(req('/api/admin/records',{...record,cluster:'vattavada'})),403);
status(await writeRecord(req('/api/admin/records',record,'https://attacker.test')),403);
status(await writeRecord(req('/api/admin/records',{...record,payload:{...record.payload,capacity:-5}})),400);
status(await writeRecord(req('/api/admin/records',record)),200);
status(await writeRecord(req('/api/admin/records',record)),409);
let catalog=await publicCatalog();assert.equal(catalog.stays.find(s=>s.id==='mankulam-stay')?.title,'Updated Mankulam stay');assert.equal(catalog.stays.find(s=>s.id==='mankulam-stay')?.clusterId,'mankulam');checks+=2;
status(await writeRecord(req('/api/admin/records',{...record,version:1,archived:true})),200);
catalog=await publicCatalog();assert.equal(catalog.stays.some(s=>s.id==='mankulam-stay'),false);checks++;
status(await writeRecord(req('/api/admin/records',{...record,version:2,archived:false})),200);
status(await audit(req('/api/admin/audit?cluster=vattavada')),403);
status(await audit(req('/api/admin/audit?cluster=mankulam')),200);
setUser('alice@example.test','imposter-id');status(await readRecords(req('/api/admin/records?cluster=mankulam&kind=stays')),403);
setUser('owner@example.test');status(await writeAccess(req('/api/admin/access',{...grant,id:m.id,active:false,version:1})),200);
setUser('alice@example.test','alice-id');status(await readRecords(req('/api/admin/records?cluster=mankulam&kind=stays')),403);
status(await writeRecord(req('/api/admin/records',{...record,version:3})),403);
setUser('owner@example.test');
status(await writeRecord(req('/api/admin/records',{cluster:'vattavada',kind:'bookings',recordId:'private-booking',version:0,published:true,archived:false,payload:{title:'Farm visit',customerName:'PRIVATE PERSON',email:'private@example.test',phone:'',start:'2026-11-10',end:'2026-11-11',guests:2,total:1000,status:'enquiry',notes:'PRIVATE NOTES',demo:true}})),200);
assert.equal(JSON.stringify(await publicCatalog()).includes('PRIVATE PERSON'),false);checks++;
const row=await env.DB.prepare('SELECT published FROM managed_records WHERE record_id = ?').bind('private-booking').first<{published:number}>();assert.equal(row?.published,0);checks++;
const eventRows=await env.DB.prepare('SELECT * FROM admin_audit').all();assert.equal(eventRows.results.length,6);checks++;
console.log(`PASS: ${checks} admin authorization, validation, concurrency, persistence, archive, audit and privacy assertions.`);
